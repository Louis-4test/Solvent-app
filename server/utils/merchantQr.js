const MERCHANT_URI_PREFIX = 'solvent://merchant/';

export const normalizeMerchantCode = (value) =>
  String(value || '').trim().toUpperCase();

export const buildMerchantQrPayload = (merchant) => {
  const code = normalizeMerchantCode(merchant?.code);
  const params = new URLSearchParams();

  if (merchant?.name) params.set('name', merchant.name);
  if (merchant?.city) params.set('city', merchant.city);

  const query = params.toString();
  return `${MERCHANT_URI_PREFIX}${encodeURIComponent(code)}${query ? `?${query}` : ''}`;
};

const codeFromJson = (value) => {
  if (!value || typeof value !== 'object') return '';

  if (value.type && value.type !== 'solvent_merchant') return '';

  return value.code || value.merchantCode || value.merchant || '';
};

/**
 * Accepts the QR URI generated by Solvent, a JSON payload, a merchant URL, or a
 * plain merchant code. The merchant is always re-validated against the database
 * before a payment is accepted.
 */
export const parseMerchantQrPayload = (payload) => {
  if (!payload) return '';

  if (typeof payload === 'object') {
    return normalizeMerchantCode(codeFromJson(payload));
  }

  const raw = String(payload).trim();
  if (!raw) return '';

  if (raw.startsWith('{')) {
    try {
      return normalizeMerchantCode(codeFromJson(JSON.parse(raw)));
    } catch {
      return '';
    }
  }

  if (raw.toLowerCase().startsWith(MERCHANT_URI_PREFIX)) {
    const rest = raw.slice(MERCHANT_URI_PREFIX.length);
    const [encodedCode] = rest.split(/[?#]/);
    try {
      return normalizeMerchantCode(decodeURIComponent(encodedCode));
    } catch {
      return normalizeMerchantCode(encodedCode);
    }
  }

  if (raw.toLowerCase().startsWith('solvent:merchant:')) {
    return normalizeMerchantCode(raw.slice('solvent:merchant:'.length).split(/[?#]/)[0]);
  }

  if (/^https?:\/\//i.test(raw)) {
    try {
      const url = new URL(raw);
      const code =
        url.searchParams.get('merchant') ||
        url.searchParams.get('merchantCode') ||
        url.searchParams.get('code') ||
        url.pathname.split('/').filter(Boolean).pop();

      return normalizeMerchantCode(code || '');
    } catch {
      return '';
    }
  }

  return normalizeMerchantCode(raw);
};

export default {
  buildMerchantQrPayload,
  parseMerchantQrPayload,
  normalizeMerchantCode
};
